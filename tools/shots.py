def _free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _build_frontend() -> None:
    print("Building the frontend...", flush=True)
    npm = shutil.which("npm") or shutil.which("npm.cmd")
    if not npm:
        sys.exit("npm is not on PATH. Pass --no-build to reuse frontend/dist.")
    subprocess.run([npm, "run", "build"], cwd=FRONTEND, check=True)


def _publish_spa() -> None:
    """Copy the built SPA where the API serves it from, as the Dockerfile does."""
    dist = FRONTEND / "dist"
    if not dist.is_dir():
        sys.exit("frontend/dist is missing. Run without --no-build.")
    static = BACKEND / "app" / "static"
    # Copy over the top rather than replacing the directory. On a OneDrive
    # folder the removal fails with "Access is denied" often enough to be a
    # nuisance, and it buys nothing: the built assets carry content hashes, so
    # a leftover from an older build is never served.
    shutil.copytree(dist, static, dirs_exist_ok=True)


def _seed(data_dir: Path, offline: bool) -> int:
    """Fill a throwaway database with a plausible few weeks of use.

    Returns the id of the account that needs a hand, which is what
    `04-needs-a-hand.png` is a picture of.
    """
    sys.path.insert(0, str(BACKEND))
    os.environ["DATA_DIR"] = str(data_dir)
    os.environ["ADMIN_PASSWORD"] = PASSWORD

    from app import db as db_module  # noqa: E402  (import after DATA_DIR is set)
    from app import models, runner, settings_store  # noqa: E402
    from app.auth import bootstrap_admin  # noqa: E402
    from app.config import get_settings  # noqa: E402
    from app.timeutil import utcnow  # noqa: E402

    get_settings()  # creates the data directory and the two generated keys
    db_module.init_db()
    now = utcnow()

    session = db_module.SessionLocal()
    try:
        bootstrap_admin()

        # A picture of a paused app is a picture of an app doing nothing, and
        # the schedule is the point. Turning it on here is safe: an account
        # loop ticks every 30 s but only runs an account whose `next_run_at`
        # has passed, and every seeded account is hours away, so nothing can
        # open a browser inside the minute this script is alive.
        settings_store.set(session, "schedule.enabled", True)
        settings_store.set(session, "notify.channel", "discord")
        settings_store.set(
            session, "notify.webhook_url",
            "https://discord.com/api/webhooks/000000000000000000/screenshots-only",
        )
        settings_store.set(session, "notify.on_run_summary", False)

        for spec in ACCOUNTS:
            last = None if spec["days_ago"] is None else now - timedelta(days=spec["days_ago"])
            session.add(
                models.Account(
                    store=spec["store"],
                    label=spec["label"],
                    status=spec["status"],
                    status_reason=spec.get("reason"),
                    status_at=last,
                    status_screenshot=spec.get("screenshot"),
                    profile_path=f"{spec['store']}-{spec['label'].lower()}",
                    enabled=spec["status"] != "never_signed_in",
                    last_run_at=last,
                    next_run_at=None if last is None else now + timedelta(hours=4 + 2 * spec['days_ago']),
                )
            )
        session.commit()
        attention = (
            session.query(models.Account)
            .filter(models.Account.status == "needs_attention")
            .first()
        )
        attention_id = attention.id if attention else 1

        # The offers, live where the store will answer.
        found = 0
        if not offline:
            for store in LIVE_STORES:
                try:
                    offers = asyncio.run(runner.discover(session, store))
                    print(f"  {store}: {len(offers)} free now", flush=True)
                    found += len(offers)
                    upcoming = asyncio.run(runner.discover_upcoming(session, store))
                    if upcoming:
                        print(f"  {store}: {len(upcoming)} announced", flush=True)
                except Exception as exc:  # a store being down must not stop a shoot
                    print(f"  {store}: discovery failed ({exc})", flush=True)

        # A row stamped a moment ago reads "Seen just now" on every card, which
        # is what a seeded database looks like and not what an install looks
        # like. Backdate them across the last two days.
        for index, row in enumerate(session.query(models.Offer).all()):
            age = timedelta(hours=2 + (index * 7) % 44)
            row.first_seen_at = now - age
            if row.free_seen_at is not None:
                row.free_seen_at = now - age
        session.commit()

        if found == 0:
            print("  no live offers; using the built-in set", flush=True)
            for spec in FALLBACK_OFFERS:
                session.add(
                    models.Offer(
                        store=spec["store"],
                        external_id=spec["external_id"],
                        title=spec["title"],
                        kind=spec["kind"],
                        url=spec["url"],
                        ends_at=now + timedelta(hours=spec["ends_in_h"]),
                        free_seen_at=now - timedelta(hours=30),
                        first_seen_at=now - timedelta(hours=30),
                    )
                )
            session.commit()

        # The ledger, hung off the offers that exist so the rows carry artwork.
        accounts = {a.store: a for a in session.query(models.Account).all()}
        by_store: dict[str, list[models.Offer]] = {}
        for offer in session.query(models.Offer).order_by(models.Offer.id).all():
            by_store.setdefault(offer.store, []).append(offer)

        used: dict[str, int] = {}
        for spec in CLAIMS:
            store = spec["store"]
            account = accounts.get(store)
            pool = by_store.get(store) or []
            if account is None or not pool:
                continue
            offer = pool[used.get(store, 0) % len(pool)]
            used[store] = used.get(store, 0) + 1
            when = now - timedelta(hours=spec["hours_ago"])
            # Runs do not all take the same time, and four rows reading
            # "in 42.0 s" is the tell that a seed wrote them.
            took = 18.0 + (spec["hours_ago"] * 7) % 51
            run = models.Run(
                account_id=account.id,
                store=store,
                status="ok",
                trigger="schedule",
                started_at=when,
                finished_at=when + timedelta(seconds=took),
                duration_s=took,
                offers_seen=len(pool),
                claimed=1 if spec["outcome"] == "claimed" else 0,
                already_owned=1 if spec["outcome"] == "already_owned" else 0,
            )
            session.add(run)
            session.flush()
            session.add(
                models.Claim(
                    account_id=account.id,
                    offer_id=offer.id,
                    run_id=run.id,
                    store=store,
                    title=offer.title,
                    kind=spec.get("kind", offer.kind),
                    image_url=offer.image_url,
                    outcome=spec["outcome"],
                    detail=spec.get("detail"),
                    reason_code=spec.get("reason_code"),
                    created_at=when,
                )
            )
        session.commit()
    finally:
        session.close()

    # The evidence picture on the account that needs a hand. Any PNG will do;
    # the container capture is the one that looks like a store page, because
    # it is one.
    shot = data_dir / "screenshots" / "epic-verify.png"
    source = DEFAULT_OUT / "08-container-screen.png"
    if source.exists():
        shot.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, shot)

    return attention_id


def _serve(data_dir: Path, port: int) -> subprocess.Popen:
    env = dict(os.environ)
    # The scheduler stays off by itself: `schedule.enabled` defaults to False
    # in a fresh database, which is what stops a screenshot run ever touching
    # a store account.
    env.update(
        DATA_DIR=str(data_dir),
        ADMIN_PASSWORD=PASSWORD,
        LOG_LEVEL="WARNING",
    )
    proc = subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "app.main:app", "--app-dir", str(BACKEND),
         "--host", "127.0.0.1", "--port", str(port), "--log-level", "warning"],
        cwd=ROOT,
        env=env,
    )
    for _ in range(120):
        if proc.poll() is not None:
            sys.exit("The API exited before it answered.")
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/health", timeout=1):
                return proc
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            time.sleep(0.5)
    proc.terminate()
    sys.exit("The API never answered /api/health.")


def _shoot(port: int, out: Path, attention_id: int) -> None:
    from playwright.sync_api import sync_playwright

    base = f"http://127.0.0.1:{port}"
    out.mkdir(parents=True, exist_ok=True)

    with sync_playwright() as play:
        # The same browser the app drives, for the same reason: it is the one
        # whose text rendering the rest of the docs were made with.
        try:
            browser = play.chromium.launch(channel="chrome")
        except Exception:
            print("Real Chrome not found; using the bundled Chromium.", flush=True)
            browser = play.chromium.launch()

        context = browser.new_context(viewport=VIEWPORT, device_scale_factor=1)
        page = context.new_page()

        # The theme is a localStorage key, so it has to be set on the origin
        # before the app's first paint or the shot catches the swap.
        page.goto(f"{base}/login", wait_until="domcontentloaded")
        page.evaluate("localStorage.setItem('trove.theme', 'dark')")

        page.goto(f"{base}/login", wait_until="domcontentloaded")
        page.fill("input[type=password]", PASSWORD)
        page.click("button[type=submit]")
        page.wait_for_url(f"{base}/", timeout=15_000)

        def shot(path: str, name: str, alt: str, full: bool = False,
                 settle: int = 1200) -> None:
            page.set_viewport_size(VIEWPORT)
            page.goto(f"{base}{path}", wait_until="networkidle")
            page.wait_for_timeout(settle)
            # Artwork loads lazily, and a half-drawn grid is exactly the
            # picture not to publish. The scroller is `<main>`, not the
            # document, so this has to scroll the element.
            page.evaluate(
                "() => { const m = document.querySelector('main');"
                " if (m) m.scrollTop = m.scrollHeight; }"
            )
            page.wait_for_timeout(600)
            page.evaluate(
                "() => { const m = document.querySelector('main');"
                " if (m) m.scrollTop = 0; }"
            )
            page.wait_for_timeout(400)

            # `full_page` is useless here for the same reason: the document
            # never scrolls, so Playwright has nothing beyond the viewport to
            # stitch. Growing the window is what actually shows the rest of a
            # long page, and it keeps the sidebar and the top bar in the shot
            # rather than a bare strip of content.
            if full:
                height = page.evaluate(
                    "() => { const m = document.querySelector('main');"
                    " return m ? m.scrollHeight + 100 : document.body.scrollHeight; }"
                )
                page.set_viewport_size(
                    {"width": VIEWPORT["width"],
                     "height": max(VIEWPORT["height"], min(int(height), 2400))}
                )
                page.wait_for_timeout(700)

            target = out / name
            page.screenshot(path=str(target))
            print(f"  {name}  {alt}", flush=True)

        shot("/", "01-overview.png", "the overview")
        shot("/offers", "03-free-now.png", "what is free")
        shot(f"/accounts/{attention_id}", "04-needs-a-hand.png",
             "an account that needs a hand", full=True)
        shot("/settings", "05-notifications.png", "notifications", full=True)
        shot("/ledger", "06-ledger.png", "the ledger")

        context.close()
        browser.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--no-build", action="store_true", help="reuse frontend/dist")
    parser.add_argument("--offline", action="store_true", help="skip live discovery")
    parser.add_argument("--keep", action="store_true", help="keep the temp data dir")
    args = parser.parse_args()

    if not args.no_build:
        _build_frontend()
    _publish_spa()

    data_dir = Path(tempfile.mkdtemp(prefix="trove-shots-"))
    print(f"Seeding {data_dir}", flush=True)
    proc = None
    try:
        attention_id = _seed(data_dir, args.offline)
        port = _free_port()
        proc = _serve(data_dir, port)
        print(f"Shooting against {port}", flush=True)
        _shoot(port, args.out, attention_id)
    finally:
        if proc is not None:
            proc.terminate()
            with contextlib.suppress(Exception):
                proc.wait(timeout=10)
        if args.keep:
            print(f"Left {data_dir} in place.", flush=True)
        else:
            shutil.rmtree(data_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
