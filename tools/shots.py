"""Regenerate the README screenshots from the app itself.

STYLE-GUIDE 17.1 asks for screenshots generated by the app rather than taken
by hand, and for a reason this repository has already been bitten by: the
pictures in the README were a release old within a week, showing a Free now
page with no store marks and a ledger with no artwork. A picture nobody can
reproduce is a picture nobody updates.

So this script builds the frontend, seeds a *throwaway* database, serves it
with the real API, drives real Chrome over Playwright and writes the files in
`docs/images/`. It never touches `DATA_DIR`, never opens a store account and
never reads a profile: the temporary directory is deleted on the way out.

    python tools/shots.py                 # build, seed, shoot, clean up
    python tools/shots.py --no-build      # reuse frontend/dist as it is
    python tools/shots.py --offline       # skip live discovery, use the seed
    python tools/shots.py --keep          # leave the temp data dir behind

**The offers are real by default.** The four sessionless adapters are asked
what is free right now (one public HTTP request each, exactly what the Check
the stores button does), so the cards carry real titles, real artwork and real
deadlines. That is the "real content" half of 17.1, and it is also a live test
of discovery. `--offline`, or any store that answers nothing, falls back to a
small built-in set so the shots still have something in them.

The accounts, claims and runs are always seeded: they are what a person's
install looks like after a few weeks, and there is no honest way to obtain
that from a fresh database. They are written to be plausible rather than
flattering - one account needs a hand, one claim was not eligible and says
why, most claims are `already_owned`, which is the true steady state.

Dark theme only, per 17.1's checklist. There used to be a light-theme copy of
the overview in `docs/images/` and nothing referenced it, which is what an
unreferenced screenshot becomes: a picture of a build nobody remembers.

What this cannot produce, and why those two files stay checked in as they are:
`02-live-view.png` needs a store challenge in front of a real account, and
`08-container-screen.png` is captured by the container smoke workflow on a
GitHub runner. Both are evidence rather than illustration.
"""
from __future__ import annotations

import argparse
import asyncio
import contextlib
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from datetime import timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND = ROOT / "backend"
FRONTEND = ROOT / "frontend"
DEFAULT_OUT = ROOT / "docs" / "images"

PASSWORD = "screenshots-only"
VIEWPORT = {"width": 1440, "height": 950}

# The stores whose discovery costs one public request and no session. Prime is
# absent on purpose: its offers only exist inside a signed-in page
# (`discovery_needs_session`), so asking it here would open a browser.
LIVE_STORES = ("epic", "steam", "itchio", "gog")


